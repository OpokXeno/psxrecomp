/* GPU-resident Native triangle setup. Keep arithmetic and rounding aligned
 * with native_attribute_planes/native_depth_plane; no CPU readback.
 * Explicit dvec component stores preserve Q16 precision on the tested NVIDIA
 * compiler, whose dynamically indexed scalar arrays rounded these to float. */
static const char *NATIVE_GPU_SETUP_CS =
    "#version 430\n"
    "#extension GL_ARB_gpu_shader_fp64 : require\n"
    "#extension GL_ARB_gpu_shader_int64 : require\n"
    "layout(local_size_x=64) in;\n"
    "struct Triangle { ivec4 xyuv[3]; ivec4 rgbz[3]; ivec4 config; ivec4 depth; };\n"
    "layout(std430,binding=0) readonly buffer Inputs { Triangle triangles[]; };\n"
    "layout(std430,binding=1) buffer Parameters { uvec4 parameters[]; };\n"
    "uniform int triangle_count;\n"
    "bool finite(double x) { return !isnan(x)&&!isinf(x); }\n"
    "ivec2 axis_limits(int lo,int hi,int dir) {\n"
    "    if(dir>0&&hi>lo)--hi;\n"
    "    if(dir<0&&hi>lo)++lo;\n"
    "    return (lo>>8)==(hi>>8)?ivec2(lo&255,hi&255):ivec2(0,255);\n"
    "}\n"
    "void set3(inout dvec3 target,int index,double value){if(index==0)target.x=value;else if(index==1)target.y=value;else target.z=value;}\n"
    "void set4(inout dvec4 target,int index,double value){if(index==0)target.x=value;else if(index==1)target.y=value;else if(index==2)target.z=value;else target.w=value;}\n"
    "void main() {\n"
    "    uint id=gl_GlobalInvocationID.x;\n"
    "    if(id>=uint(triangle_count))return;\n"
    "    Triangle t=triangles[id];\n"
    "    uint b=id*14u,s=uint(triangle_count)*14u+id*6u;\n"
    "    precise dvec3 x,y,v[5];\n"
    "    vec3 fx,fy;\n"
    "    ivec3 us,vs;\n"
    "    bool integral=true;\n"
    "    for(int i=0;i<3;++i) {\n"
    "        set3(x,i,double(t.xyuv[i].x)/65536.0lf+double(t.config.z));\n"
    "        set3(y,i,double(t.xyuv[i].y)/65536.0lf+double(t.config.w));\n"
    "        fx[i]=float(x[i]);\n"
    "        fy[i]=float(y[i]);\n"
    "        us[i]=int(floor(double(t.xyuv[i].z)/65536.0lf));\n"
    "        vs[i]=int(floor(double(t.xyuv[i].w)/65536.0lf));\n"
    "        set3(v[0],i,double(t.xyuv[i].z)/65536.0lf);\n"
    "        set3(v[1],i,double(t.xyuv[i].w)/65536.0lf);\n"
    "        int c=t.config.y!=0?i:0;\n"
    "        for(int a=2;a<5;++a)set3(v[a],i,double(t.rgbz[c][a-2]));\n"
    "        integral=integral&&x[i]==floor(x[i])&&y[i]==floor(y[i])&&\n"
    "            (t.xyuv[i].z%65536)==0&&(t.xyuv[i].w%65536)==0;\n"
    "    }\n"
    "    // gpu_uv.h intentionally subtracts float positions before double products.\n"
    "    precise double dudx=-double(fy[1]-fy[0])*double(us[2])-double(fy[2]-fy[1])*double(us[0])-double(fy[0]-fy[2])*double(us[1]);\n"
    "    precise double dvdx=-double(fy[1]-fy[0])*double(vs[2])-double(fy[2]-fy[1])*double(vs[0])-double(fy[0]-fy[2])*double(vs[1]);\n"
    "    precise double dudy= double(fx[1]-fx[0])*double(us[2])+double(fx[2]-fx[1])*double(us[0])+double(fx[0]-fx[2])*double(us[1]);\n"
    "    precise double dvdy= double(fx[1]-fx[0])*double(vs[2])+double(fx[2]-fx[1])*double(vs[0])+double(fx[0]-fx[2])*double(vs[1]);\n"
    "    precise double fa=double(fx[1]-fx[0])*double(fy[2]-fy[0])-double(fx[2]-fx[0])*double(fy[1]-fy[0]);\n"
    "    int du=fa==0.0lf?0:dudx==0.0lf?int(sign(dudy)):dudy==0.0lf?int(sign(dudx)):0;\n"
    "    int dv=fa==0.0lf?0:dvdx==0.0lf?int(sign(dvdy)):dvdy==0.0lf?int(sign(dvdx)):0;\n"
    "    if(fa<0.0lf){du=-du;dv=-dv;}\n"
    "    ivec2 lu=axis_limits(min(us[0],min(us[1],us[2])),max(us[0],max(us[1],us[2])),du);\n"
    "    ivec2 lv=axis_limits(min(vs[0],min(vs[1],vs[2])),max(vs[0],max(vs[1],vs[2])),dv);\n"
    "    parameters[b+3u]=uvec4(lu.x,lv.x,lu.y,lv.y);\n"
    "    int core=x[1]<=x[0]?(x[2]<=x[1]?2:1):(x[2]<x[0]?2:0);\n"
    "    parameters[b+5u]=floatBitsToUint(vec4(float(x[core]),float(y[core]),integral?1.0lf:2.0lf,0.0lf));\n"
    "    precise double area=(x[1]-x[0])*(y[2]-y[0])-(x[2]-x[0])*(y[1]-y[0]);\n"
    "    double scale=double(t.config.x);\n"
    "    precise dvec4 uv_step;\n"
    "    for(int a=0;a<5;++a) {\n"
    "        precise double seed=0.0lf,dx=0.0lf,dy=0.0lf;\n"
    "        uvec3 dda=uvec3(0);\n"
    "        if(area!=0.0lf) {\n"
    "            if(a>=2&&t.config.y==0) {\n"
    "                seed=v[a][0]+0.5lf;\n"
    "                dda.x=uint(int64_t(v[a][0])*4096l+2048l)&1048575u;\n"
    "            } else {\n"
    "                precise double nx=(v[a][1]-v[a][0])*(y[2]-y[0])-(v[a][2]-v[a][0])*(y[1]-y[0]);\n"
    "                precise double ny=(x[1]-x[0])*(v[a][2]-v[a][0])-(x[2]-x[0])*(v[a][1]-v[a][0]);\n"
    "                dx=nx/area;dy=ny/area;\n"
    "                bool mirror=a<2&&((dx<0.0lf&&dy==0.0lf)||(dy<0.0lf&&dx==0.0lf));\n"
    "                precise double bias=a<2?0.5lf/scale+(mirror?1.0lf-1.0lf/scale:0.0lf):0.5lf;\n"
    "                seed=v[a][core]+bias;\n"
    "                if(integral) {\n"
    "                    int64_t den=int64_t(area)*int64_t(t.config.x);\n"
    "                    int64_t sx=int64_t(nx)*4096l/den,sy=int64_t(ny)*4096l/den;\n"
    "                    int64_t q=int64_t(v[a][core])*4096l+\n"
    "                        (a<2?2048l/int64_t(t.config.x)+(mirror?4096l-4096l/int64_t(t.config.x):0l):2048l);\n"
    "                    dda=uvec3(uint(q),uint(sx),uint(sy))&1048575u;\n"
    "                    seed=double(q)/4096.0lf;\n"
    "                    dx=double(sx)*scale/4096.0lf;dy=double(sy)*scale/4096.0lf;\n"
    "                }\n"
    "            }\n"
    "        }\n"
    "        parameters[b+9u+uint(a)]=integral?uvec4(dda,0u):floatBitsToUint(vec4(float(seed),float(dx),float(dy),0.0lf));\n"
    "        if(a<2){set4(uv_step,a,dx/scale);set4(uv_step,a+2,dy/scale);}\n"
    "    }\n"
    "    if(parameters[b+7u].z>1u)parameters[b+6u]=floatBitsToUint(vec4(uv_step[0],uv_step[1],uv_step[2],uv_step[3]));\n"
    "    // Match native_depth_plane, including its constant far-corner fallback.\n"
    "    if(t.depth.z==0)return;\n"
    "    bool valid=t.depth.x!=0&&area!=0.0lf&&finite(area)&&finite(x[0])&&finite(y[0])&&\n"
    "        abs(x[0])<=1048576.0lf&&abs(y[0])<=1048576.0lf;\n"
    "    precise dvec3 d;\n"
    "    for(int i=0;i<3;++i) {\n"
    "        valid=valid&&t.rgbz[i].w>0;\n"
    "        set3(d,i,t.rgbz[i].w>0?1099511627776.0lf/double(t.rgbz[i].w):0.0lf);\n"
    "    }\n"
    "    int show=t.depth.x==0?0:3;\n"
    "    ivec4 depth_plane=ivec4(0);\n"
    "    ivec2 depth_origin=ivec2(0);\n"
    "    if(valid) {\n"
    "        precise double ox=floor(x[0]),oy=floor(y[0]);\n"
    "        precise double dx=((d[1]-d[0])*(y[2]-y[0])-(d[2]-d[0])*(y[1]-y[0]))/area;\n"
    "        precise double dy=((x[1]-x[0])*(d[2]-d[0])-(x[2]-x[0])*(d[1]-d[0]))/area;\n"
    "        precise double a=roundEven(dx*256.0lf),c=roundEven(dy*256.0lf);\n"
    "        precise double n=roundEven((d[0]+dx*(ox-x[0])+dy*(oy-y[0]))*256.0lf);\n"
    "        depth_origin=ivec2(ox,oy);\n"
    "        if(finite(dx)&&finite(dy)&&abs(a)<=4194304.0lf&&abs(c)<=4194304.0lf&&n>=256.0lf&&n<1073741824.0lf)\n"
    "            depth_plane=ivec4(int(n),int(a),int(c),t.config.x);\n"
    "        else {\n"
    "            precise double far_key=min(min(d[0],d[1]),d[2])*256.0lf;\n"
    "            valid=finite(far_key)&&far_key>=256.0lf;\n"
    "            if(valid)depth_plane=ivec4(int(min(far_key,1073741823.0lf)),0,0,t.config.x);\n"
    "        }\n"
    "    }\n"
    "    if(valid)show=t.depth.x==2?2:1;\n"
    "    parameters[b+2u]=uvec4(valid?1:0,valid&&t.depth.x==2?2:1,t.depth.w,valid?t.depth.y:0);\n"
    "    if(valid)parameters[b+4u]=uvec4(depth_plane);\n"
    "    if(valid)parameters[b+8u].yz=uvec2(depth_origin);\n"
    "    parameters[s+2u].y=uint(show);\n"
    "}\n"
    "\n";

/* An order-sensitive, parallel fingerprint of the immutable RGBA8 image.
 * The full legacy byte digest remains the audit/probe format. */
static const char *NATIVE_GPU_IMAGE_HASH_CS =
    "#version 430\n"
    "#extension GL_ARB_gpu_shader_int64 : require\n"
    "layout(local_size_x=128) in;\n"
    "layout(binding=9) uniform sampler2D source_image;\n"
    "layout(std430,binding=0) writeonly buffer Results { uvec4 results[]; };\n"
    "shared uint64_t hashes[128];\n"
    "shared uint visible[128];\n"
    "uint64_t mix64(uint64_t x) {\n"
    "    x=(x^(x>>30))*0xbf58476d1ce4e5b9ul;\n"
    "    x=(x^(x>>27))*0x94d049bb133111ebul;\n"
    "    return x^(x>>31);\n"
    "}\n"
    "void main() {\n"
    "    ivec2 size=textureSize(source_image,0);\n"
    "    uint count=uint(size.x)*uint(size.y),lane=gl_LocalInvocationID.x;\n"
    "    uint64_t hash=0ul;uint seen=0u;\n"
    "    for(uint i=gl_GlobalInvocationID.x;i<count;i+=gl_NumWorkGroups.x*128u) {\n"
    "        uint rgba=packUnorm4x8(texelFetch(source_image,ivec2(i%uint(size.x),i/uint(size.x)),0));\n"
    "        hash^=mix64(uint64_t(rgba)^(uint64_t(i)*0x9e3779b97f4a7c15ul));\n"
    "        seen+=uint((rgba&0xffffffu)!=0u);\n"
    "    }\n"
    "    hashes[lane]=hash;visible[lane]=seen;barrier();\n"
    "    for(uint stride=64u;stride!=0u;stride>>=1u) {\n"
    "        if(lane<stride){hashes[lane]^=hashes[lane+stride];visible[lane]+=visible[lane+stride];}\n"
    "        barrier();\n"
    "    }\n"
    "    if(lane==0u)results[gl_WorkGroupID.x]=uvec4(uint(hashes[0]),uint(hashes[0]>>32),visible[0],0u);\n"
    "}\n";
