#!/usr/bin/env python3
"""embed_glsl.py - emit the OpenGL text of the shared shaders as one C header.

The shaders under runtime/shaders/ are written once and compiled for Vulkan by
embed_spirv.py (glslc). The same files are the OpenGL sources: this tool resolves
their `#include "file"` lines, strips comments, replaces the leading `#version`
line and writes one `static const char *const glsl_<name>_<stage>[_<SUFFIX>]`
string per program, which gpu_gl_renderer.c hands to glShaderSource.

Only shaders that carry a `//! gl_version <N>` directive are emitted; the others
(Vulkan-only shaders) are skipped. Directives (read from the shader file itself):

    //! gl_version 330
        GL #version of the base string `glsl_<name>_<stage>`.
    //! gl_variant <SUFFIX> <N> [<DEFINE>[=<value>] ...]
        An extra string `glsl_<name>_<stage>_<SUFFIX>` with `#version <N>` and a
        `#define DEFINE value` line (value defaults to 1) after it. Runtime
        variants are therefore plain strings; nothing is assembled at run time.

The first line of every shader must be `#version 450` (the Vulkan version); it is
the only line replaced. Includes are inlined in place with no include guard,
exactly like glslc, so a file included twice appears twice.

Usage: embed_glsl.py --out <header.h> [--depfile <deps.d>] shader1.vert shader2.frag ...
"""
import argparse, os, re, sys

STAGE = {".vert": "vert", ".frag": "frag", ".comp": "comp"}
INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')
GL_VERSION_RE = re.compile(r"^//! gl_version (\d+)\s*$")
GL_VARIANT_RE = re.compile(r"^//! gl_variant (\S+) (\d+)((?: \S+)*)\s*$")
SUFFIX_RE = re.compile(r"^[A-Za-z0-9_]+$")
DEFINE_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)(?:=(\S+))?$")
COMMENT_RE = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)


def strip_comments(text):
    """GLSL has no string literals, so a comment scan needs no quoting rules."""
    def blank(m):
        return "\n" * m.group(0).count("\n")
    return COMMENT_RE.sub(blank, text)


def resolve(path, deps):
    """Return the text of path with every #include inlined (comments kept)."""
    if path not in deps:
        deps.append(path)
    out = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f.read().split("\n"):
            m = INCLUDE_RE.match(line)
            if m:
                out.append(resolve(os.path.join(os.path.dirname(path), m.group(1)), deps))
            else:
                out.append(line)
    return "\n".join(out)


def directives(path):
    base, variants = None, []
    with open(path, "r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.rstrip("\r\n")
            m = GL_VERSION_RE.match(line)
            if m:
                base = m.group(1)
                continue
            m = GL_VARIANT_RE.match(line)
            if not m:
                continue
            suffix, version, defines = m.group(1), m.group(2), m.group(3).split()
            where = "%s:%d" % (path, lineno)
            if not SUFFIX_RE.match(suffix):
                raise ValueError("%s: bad variant suffix '%s'" % (where, suffix))
            if any(s == suffix for s, _, _ in variants):
                raise ValueError("%s: duplicate variant '%s'" % (where, suffix))
            lines = []
            for d in defines:
                dm = DEFINE_RE.match(d)
                if not dm:
                    raise ValueError("%s: malformed define '%s'" % (where, d))
                lines.append("#define %s %s" % (dm.group(1), dm.group(2) or "1"))
            variants.append((suffix, version, lines))
    return base, variants


def c_literal(text):
    rows = []
    for line in text.split("\n"):
        line = line.rstrip()
        if line.strip():
            rows.append('    "%s\\n"' % line.replace("\\", "\\\\").replace('"', '\\"'))
    return "\n".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--depfile")
    ap.add_argument("shaders", nargs="+")
    a = ap.parse_args()

    out = ["/* Auto-generated by embed_glsl.py - do not edit. */",
           "#ifndef PSX_GL_SHADERS_H", "#define PSX_GL_SHADERS_H", ""]
    deps, names = [], []
    try:
        for sh in a.shaders:
            name, ext = os.path.splitext(os.path.basename(sh))
            if ext not in STAGE:
                raise ValueError("%s: unsupported extension '%s'" % (sh, ext))
            base, variants = directives(sh)
            if base is None:
                continue
            text = strip_comments(resolve(sh, deps))
            first, _, rest = text.partition("\n")
            if first.strip() != "#version 450":
                raise ValueError("%s: first line must be '#version 450'" % sh)
            ident = "glsl_%s_%s" % (name.replace("-", "_"), STAGE[ext])
            for suffix, version, defines in [(None, base, [])] + variants:
                arr = ident if suffix is None else "%s_%s" % (ident, suffix)
                names.append(arr)
                body = "\n".join(["#version " + version] + defines) + "\n" + rest
                out.append("static const char *const %s =\n%s;\n" % (arr, c_literal(body)))
    except (ValueError, OSError) as e:
        sys.stderr.write("embed_glsl.py: %s\n" % e)
        return 1
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        sys.stderr.write("embed_glsl.py: duplicate output names: %s\n" % ", ".join(dupes))
        return 1
    out.append("#endif")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    if a.depfile:
        def esc(p):
            return p.replace("$", "$$").replace(" ", "\\ ").replace("#", "\\#")
        with open(a.depfile, "w") as f:
            f.write(esc(a.out) + ": " + " ".join(esc(d) for d in deps) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
